function median(values: readonly number[]): number {
  const sorted = [...values].sort((left, right) => left - right)
  return sorted[Math.floor(sorted.length / 2)] ?? 0
}

function sample(label: string, operation: () => void): Sample {
  const values: number[] = []
  for (let iteration = 0; iteration < ITERATIONS; iteration += 1) {
    const start = performance.now()
    operation()
    values.push(performance.now() - start)
  }
  return { label, values, unit: 'ms' }
}

async function asyncSample(label: string, operation: () => Promise<void>): Promise<Sample> {
  const values: number[] = []
  for (let iteration = 0; iteration < ITERATIONS; iteration += 1) {
    const start = performance.now()
    await operation()
    values.push(performance.now() - start)
  }
  return { label, values, unit: 'ms' }
}

function formatSample(value: Sample): string {
  return `${median(value.values).toFixed(2)} ms median (${value.values
    .map((item) => item.toFixed(2))
    .join(', ')}; ${value.unit})`
}

