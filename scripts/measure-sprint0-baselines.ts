async function measureOcrCancellation(): Promise<void> {
  const parserResult = makeOcrParserResult()
  const controller = new AbortController()
  const canvas = { width: 600, height: 800, getContext: () => ({}) } as unknown as HTMLCanvasElement
  const start = performance.now()
  try {
    await runOcrOrchestration(
      {
        parserResult,
        parserEntries: projectParserEntries(parserResult, now()),
        pdf: { numPages: 4, getPage: async () => ({}) },
        settings: { mode: 'balanced', ocrLanguages: ['eng'] }
      },
      {
        signal: controller.signal,
        dependencies: {
          rasterize: async (documentId, _pdf, pages) => {
            controller.abort()
            return pages.map((pageNumber) => ({
              documentId,
              pageNumber,
              image: canvas,
              width: canvas.width,
              height: canvas.height
            }))
          },
          recognize: async () => []
        }
      }
    )
  } catch (error) {
    if (!(error instanceof DOMException) || error.name !== 'AbortError') throw error
  }
  if (canvas.width !== 0 || canvas.height !== 0)
    throw new Error('OCR canvas cleanup baseline failed.')
  ocrCancellationSamples.push(performance.now() - start)
}

const ocrCancellationSamples: number[] = []

async function main(): Promise<void> {
  const project = makeProject()
  const reviewOptions = makeReviewOptions()
  const samples: Sample[] = []
  const filterResult = filterReviewEntries(project.entries, reviewOptions)
  const financialStats = calculateStatementStats(
    project.entries,
    {
      amountColumns: ['money-out', 'money-in', 'balance'],
      dateSource: 'detected-date',
      descriptionSource: 'detected-description',
      referenceSource: 'entry-notes',
      categorySource: 'entry-category'
    },
    'all'
  )

  samples.push(
    sample('review filtering (2,000 entries)', () => {
      filterReviewEntries(project.entries, reviewOptions)
    })
  )
  samples.push(
    await asyncSample('incremental review filtering (2,000 entries)', async () => {
      await filterInChunks(project.entries, (entry) => entry.normalizedText.includes('northwind'))
    })
  )
  samples.push(
    sample('review navigation (2,000 entries)', () => {
      let checksum = 0
      for (let index = 0; index < filterResult.length; index += 1) {
        checksum += filterResult[index]?.id.length ?? 0
      }
      if (checksum === 0) throw new Error('Review navigation baseline produced no entries.')
    })
  )
  samples.push(
    sample('financial mapping and stats (2,000 entries)', () => {
      calculateStatementStats(
        project.entries,
        {
          amountColumns: ['money-out', 'money-in', 'balance'],
          dateSource: 'detected-date',
          descriptionSource: 'detected-description',
          referenceSource: 'entry-notes',
          categorySource: 'entry-category'
        },
        'all'
      )
    })
  )
  samples.push(
    sample('export preview render plan (2,000 entries)', () => {
      buildKeptExportRenderPlan(makeExportRows(project.entries), makeExportTemplate())
    })
  )

  const tempRoot = await mkdtemp(join(tmpdir(), 'exact-extract-sprint0-'))
  try {
    const store = new ProjectStore(tempRoot)
    await asyncSample('project save and reopen (2,000 pages / 2,000 entries)', async () => {
      await store.save(project)
      const loaded = await store.load(project.id)
      if (loaded.pages.length !== PAGE_COUNT || loaded.entries.length !== ENTRY_COUNT) {
        throw new Error('Project baseline reopened with incomplete data.')
      }
    }).then((result) => samples.push(result))
  } finally {
    await rm(tempRoot, { recursive: true, force: true })
  }

  for (let iteration = 0; iteration < ITERATIONS; iteration += 1) await measureOcrCancellation()
  samples.push({
    label: 'OCR cancellation and canvas cleanup',
    values: ocrCancellationSamples,
    unit: 'ms'
  })

  const report = [
    '# Sprint 0 performance baseline',
    '',
    `Generated: ${now()}`,
    `Node: ${process.version}`,
    `Fixture profile: ${PAGE_COUNT} pages / ${ENTRY_COUNT} entries`,
    `Iterations per measurement: ${ITERATIONS}`,
    '',
    '## Representative fixtures',
    '',
    '| ID | Kind | Fixture | Purpose |',
    '| --- | --- | --- | --- |',
    ...representativeFixtures.map(
      (fixture) => `| ${fixture.id} | ${fixture.kind} | ${fixture.fixture} | ${fixture.purpose} |`
    ),
    '',
    '## Measurements',
    '',
    '| Operation | Median | Target |',
    '| --- | ---: | ---: |',
    ...samples.map((value) => {
      const target = value.label.includes('project save')
        ? '< 1,000 ms'
        : value.label.includes('OCR')
          ? '< 100 ms'
          : value.label.includes('export')
            ? '< 500 ms'
            : '< 250 ms'
      return `| ${value.label} | ${formatSample(value)} | ${target} |`
    }),
    '',
    '## Interpretation',
    '',
    '- These are repeatable Node-side baselines, not claims about every installed machine.',
    '- OCR cancellation uses injected rasterization/recognition dependencies to measure orchestration cancellation and canvas cleanup without downloading or running a language model.',
    '- Future review, report, persistence, OCR, and export changes should rerun `npm run benchmark:sprint0` and compare medians against this profile.',
    '- The 2,000-page profile is intentionally generated so the benchmark does not depend on storing a huge binary fixture in the repository.'
  ].join('\n')

  process.stdout.write(`${report}\n`)

  // Keep the variable in the benchmark output path so the financial fixture is exercised too.
  if (financialStats.rows.length === 0)
    throw new Error('Financial fixture profile unexpectedly empty.')
}

main().catch((error: unknown) => {
  console.error(error)
  process.exitCode = 1
})
