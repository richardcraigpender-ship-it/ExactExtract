function now(): string {
  return new Date().toISOString()
}

function makeEntry(index: number, timestamp: string): ProjectEntry {
  const status: ReviewStatus = index % 11 === 0 ? 'maybe' : index % 17 === 0 ? 'exclude' : 'keep'
  const source = index % 5 === 0 ? 'ocr' : index % 7 === 0 ? 'merged' : 'parser'
  const amount = (index + 1).toFixed(2)
  return {
    id: `entry-${index + 1}`,
    rawText: `1 Mar 2026 Northwind Merchant ${index + 1} £${amount} £10,000.00`,
    normalizedText: `1 Mar 2026 Northwind Merchant ${index + 1} £${amount} £10,000.00`,
    payee: `Northwind Merchant ${index % 100}`,
    source,
    status,
    confidence: 0.55 + ((index * 17) % 45) / 100,
    regions: [
      {
        documentId: 'large-performance-document',
        pageNumber: (index % PAGE_COUNT) + 1,
        bbox: {
          x: 40,
          y: 80,
          width: 300,
          height: 14,
          coordinateSpace: 'pdf-points'
        }
      }
    ],
    category: index % 3 === 0 ? 'accounting-expense' : 'accounting-entry',
    tags: [
      'accounting',
      ...(index % 11 === 0 ? ['review:maybe'] : []),
      ...(index % 13 === 0 ? ['duplicate-candidate'] : [])
    ],
    createdAt: timestamp,
    updatedAt: timestamp
  }
}

function makeProject(): ProjectState {
  const timestamp = now()
  const store = new ProjectStore('sprint-0-benchmark-placeholder')
  const project = store.create('Sprint 0 large project', 'sprint-0-large-project')
  project.documents = [
    {
      id: 'large-performance-document',
      path: 'sprint-0-large-project.pdf',
      name: 'sprint-0-large-project.pdf',
      size: 1024 * 1024,
      pageCount: PAGE_COUNT,
      kind: 'tabular',
      importedAt: timestamp
    }
  ]
  project.pages = Array.from({ length: PAGE_COUNT }, (_, index) => ({
    documentId: 'large-performance-document',
    pageNumber: index + 1,
    width: 612,
    height: 792,
    rotation: 0 as const,
    kind: index % 5 === 0 ? ('mixed' as const) : ('text' as const),
    confidence: 0.9
  }))
  project.entries = Array.from({ length: ENTRY_COUNT }, (_, index) => makeEntry(index, timestamp))
  project.preflight = [
    {
      documentId: 'large-performance-document',
      kind: 'tabular',
      confidence: 0.9,
      completedAt: timestamp,
      pages: project.pages.map((page) => ({
        pageNumber: page.pageNumber,
        kind: page.kind,
        characterCount: 140,
        confidence: page.confidence ?? 0.9,
        ocrRecommended: page.kind !== 'text',
        rotation: page.rotation
      }))
    }
  ]
  return project
}

